/**
 * Документированная приблизительная модель.
 *
 * Концентрация = масса этанола в теле / объём распределения.
 * Объём распределения = коэффициент Видмарка × масса тела; при указанном росте
 * коэффициент считается из общей воды тела (Hume–Weyers, 1971) с поправкой
 * на долю воды в крови.
 *
 * Всасывание не мгновенное: это кинетика первого порядка из «желудка».
 * Выведение — примерно постоянная скорость (0,15 ‰/ч), но не ниже нуля.
 */
export const BLOOD_MODEL = {
  /** Полувыведение из желудка без еды, минуты. */
  absorptionHalfLifeMin: 12,
  absorptionHalfLifeSpreadMin: { min: 8, max: 18 },
  /** Максимальная скорость выведения, ‰/ч (≈ г/л/ч). Классическая оценка — 0,15. */
  eliminationPerMillePerHour: 0.15,
  eliminationSpreadPerMillePerHour: { min: 0.1, max: 0.2 },
  /**
   * Константа Михаэлиса, ‰: при концентрации около неё скорость выведения
   * уже вдвое меньше максимальной. Поэтому у нуля кривая затухает медленнее
   * и маленькая доза не «удаляется» за одну минуту.
   */
  michaelisConstantPerMille: 0.1,
  /** Доля воды в цельной крови: переводит общую воду тела в объём распределения. */
  bloodWaterFraction: 0.8,
  /** Классические коэффициенты Видмарка, если рост не указан. */
  widmarkMen: 0.68,
  widmarkWomen: 0.55,
  /** Рамки, в которых держим коэффициент Видмарка: защита от абсурда. */
  distributionFactorBounds: { min: 0.45, max: 0.85 },
  /** Разброс объёма распределения относительно центральной оценки. */
  volumeSpread: { min: 0.88, max: 1.12 },
  /** Ниже этого значения считаем, что расчётная кривая дошла до нуля, ‰. */
  zeroThresholdPerMille: 0.01,
  /** Максимальное время расчёта, часы. */
  maxHorizonHours: 48,
} as const;

